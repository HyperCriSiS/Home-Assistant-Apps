"""Central upstream pins, generated HA build arguments and safe update proposals."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
REPOSITORIES = {'cwa': 'crocodilestick/Calibre-Web-Automated', 'shelfmark': 'calibrain/shelfmark'}


def load_manifest():
    data = json.loads((ROOT / 'upstream.json').read_text())
    for name, repository in REPOSITORIES.items():
        item = data[name]
        if (item['repository'] != repository
                or not re.fullmatch(r'[0-9a-f]{40}', item['commit'])
                or not re.fullmatch(r'[0-9a-f]{64}', item['sha256'])
                or not re.fullmatch(r'v?\d+\.\d+\.\d+', item['version'])):
            raise ValueError('Invalid upstream pin: ' + name)
    return data


def arguments(data):
    return {
        'CWA_VERSION': data['cwa']['version'], 'CWA_REF': data['cwa']['commit'],
        'CWA_SHA256': data['cwa']['sha256'], 'SHELFMARK_REF': data['shelfmark']['commit'],
        'SHELFMARK_SHA256': data['shelfmark']['sha256'],
        'SHELFMARK_PYTHON': data['shelfmark_python'],
        'CALIBRE_RELEASE': data['calibre'], 'KEPUBIFY_RELEASE': data['kepubify'],
    }


def render(data):
    header = ('# Generated by scripts/upstreams.py; edit upstream.json instead.\n'
              'build_from:\n'
              '  aarch64: ghcr.io/home-assistant/aarch64-base-debian:bookworm\n'
              '  amd64: ghcr.io/home-assistant/amd64-base-debian:bookworm\n'
              'squash: false\nargs:\n')
    return header + ''.join(f'  {key}: "{value}"\n' for key, value in arguments(data).items())


def request(url, github=False):
    headers = {'User-Agent': 'Calibre-AIO-upstream-updater'}
    if github and os.environ.get('GH_TOKEN'):
        headers['Authorization'] = 'Bearer ' + os.environ['GH_TOKEN']
    return urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=60)


def latest(name):
    repository = REPOSITORIES[name]
    with request(f'https://api.github.com/repos/{repository}/releases/latest', True) as response:
        release = json.load(response)
    version = release['tag_name']
    if release.get('draft') or release.get('prerelease') or not re.fullmatch(r'v?\d+\.\d+\.\d+', version):
        raise ValueError('Only stable version tags are eligible')
    with request(f'https://api.github.com/repos/{repository}/commits/{version}', True) as response:
        commit = json.load(response)['sha']
    if not re.fullmatch(r'[0-9a-f]{40}', commit):
        raise ValueError('Invalid upstream commit')
    digest = hashlib.sha256()
    with request(f'https://github.com/{repository}/archive/{commit}.tar.gz') as response:
        for chunk in iter(lambda: response.read(1024 * 1024), b''):
            digest.update(chunk)
    return dict(repository=repository, version=version, commit=commit, sha256=digest.hexdigest())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['check', 'render', 'args', 'update'])
    parser.add_argument('--component', choices=['all', 'cwa', 'shelfmark'], default='all')
    args = parser.parse_args()
    data = load_manifest()
    if args.command == 'args':
        config = (ROOT / 'config.yaml').read_text()
        version = re.search(r'^version: "([0-9.]+)"$', config, re.M)
        if not version:
            raise ValueError('Unexpected app version')
        print('BUILD_VERSION=' + version[1])
        print('\n'.join(f'{key}={value}' for key, value in arguments(data).items()))
        return
    if args.command == 'update':
        updated = dict(data)
        for name in REPOSITORIES:
            if args.component in ('all', name):
                candidate = latest(name)
                # Never silently replace the contents of an already-pinned release.
                if candidate['version'] == data[name]['version']:
                    if candidate != data[name]:
                        raise ValueError('Pinned release provenance changed: ' + name)
                else:
                    if tuple(map(int, candidate['version'].lstrip('v').split('.'))) <= tuple(
                            map(int, data[name]['version'].lstrip('v').split('.'))):
                        raise ValueError('Refusing an upstream downgrade: ' + name)
                    updated[name] = candidate
        if updated == data:
            print('No upstream updates')
            return
        data = updated
        config = (ROOT / 'config.yaml').read_text()
        match = re.search(r'^version: "(\d+)\.(\d+)\.(\d+)"$', config, re.M)
        if not match:
            raise ValueError('Unexpected app version format')
        version = f'{match[1]}.{match[2]}.{int(match[3]) + 1}'
        (ROOT / 'upstream.json').write_text(json.dumps(data, indent=2) + '\n')
        (ROOT / 'config.yaml').write_text(config.replace(match[0], f'version: "{version}"', 1))
        changelog = ROOT / 'CHANGELOG.md'
        changelog.write_text(f'# {version}\n\n- Update CWA to {data["cwa"]["version"]} and '
                             f'Shelfmark to {data["shelfmark"]["version"]}; integration checks required.\n\n'
                             + changelog.read_text())
    generated = render(data)
    if args.command == 'check':
        if (ROOT / 'build.yaml').read_text() != generated:
            raise SystemExit('build.yaml differs from upstream.json; run scripts/upstreams.py render')
    else:
        (ROOT / 'build.yaml').write_text(generated)


if __name__ == '__main__':
    main()
