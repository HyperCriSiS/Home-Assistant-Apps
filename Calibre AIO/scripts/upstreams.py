"""Central upstream pins, generated HA build arguments and safe update proposals."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import time
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
REPOSITORIES = {'cwa': 'crocodilestick/Calibre-Web-Automated', 'shelfmark': 'calibrain/shelfmark'}
LABELS = {'cwa': 'CWA', 'shelfmark': 'Shelfmark'}
# App releases use the repository's CalVer scheme: vYYYY.MM.DD, -N for a further release on one day.
APP_VERSION = r'v\d{4}\.\d{2}\.\d{2}(?:-\d+)?'
VERSION_LINE = re.compile(r'^version: "(' + APP_VERSION + r')"$', re.M)
DESCRIPTION = 'Book discovery and Calibre library management in one interface'
CHANGELOG_HEAD = '# Changelog\n\n'
# Files the updater rewrites besides upstream.json and build.yaml; the release
# gate regenerates them from the stable branch and accepts no other change.
VERSIONED_FILES = ('config.yaml', 'CHANGELOG.md', 'README.md', 'NOTICE.md')


def load_manifest():
    data = json.loads((ROOT / 'upstream.json').read_text())
    for name, repository in REPOSITORIES.items():
        item = data[name]
        if (item['repository'] != repository
                or not re.fullmatch(r'[0-9a-f]{40}', item['commit'])
                or not re.fullmatch(r'[0-9a-f]{64}', item['sha256'])
                or not re.fullmatch(r'v?\d+\.\d+\.\d+', item['version'])):
            raise ValueError('Invalid upstream pin: ' + name)
    for name, keys in (('calibre_sha256', ('x86_64', 'arm64')),
                       ('kepubify_sha256', ('linux-64bit', 'linux-arm64'))):
        if (set(data[name]) != set(keys)
                or not all(re.fullmatch(r'[0-9a-f]{64}', value) for value in data[name].values())):
            raise ValueError('Invalid upstream pin: ' + name)
    return data


def arguments(data):
    return {
        'CWA_VERSION': data['cwa']['version'], 'CWA_REF': data['cwa']['commit'],
        'CWA_SHA256': data['cwa']['sha256'], 'SHELFMARK_REF': data['shelfmark']['commit'],
        'SHELFMARK_SHA256': data['shelfmark']['sha256'],
        'SHELFMARK_PYTHON': data['shelfmark_python'],
        'CALIBRE_RELEASE': data['calibre'], 'KEPUBIFY_RELEASE': data['kepubify'],
        'CALIBRE_SHA256_X86_64': data['calibre_sha256']['x86_64'],
        'CALIBRE_SHA256_ARM64': data['calibre_sha256']['arm64'],
        'KEPUBIFY_SHA256_64BIT': data['kepubify_sha256']['linux-64bit'],
        'KEPUBIFY_SHA256_ARM64': data['kepubify_sha256']['linux-arm64'],
    }


def render(data):
    header = ('# Generated by scripts/upstreams.py; edit upstream.json instead.\n'
              'build_from:\n'
              '  aarch64: ghcr.io/home-assistant/aarch64-base-debian:trixie\n'
              '  amd64: ghcr.io/home-assistant/amd64-base-debian:trixie\n'
              'squash: false\nargs:\n')
    return header + ''.join(f'  {key}: "{value}"\n' for key, value in arguments(data).items())


def app_version(config):
    match = VERSION_LINE.search(config)
    if not match:
        raise ValueError('Unexpected app version format')
    return match[1]


def next_version(current, today=None):
    """The next CalVer release: today's date, or -N when a release already exists for today."""
    base = 'v' + (today or time.strftime('%Y.%m.%d', time.gmtime()))
    if not re.fullmatch(APP_VERSION, current):
        return base
    stem, _, suffix = current.partition('-')
    if stem != base:
        return base
    return f'{base}-{int(suffix or 1) + 1}'


def description(data):
    return f'CWA {data["cwa"]["version"]} and Shelfmark {data["shelfmark"]["version"]} - {DESCRIPTION}'


def badge(name, data):
    version = data[name]['version']
    return (f'[![{LABELS[name]} version](https://img.shields.io/badge/{LABELS[name]}-{version}-B49A64)]'
            f'(https://github.com/{REPOSITORIES[name]}/releases/tag/{version})')


def _replace_line(text, pattern, line, label):
    text, count = re.subn(pattern, lambda _: line, text, count=1, flags=re.M)
    if count != 1:
        raise ValueError('Cannot update ' + label)
    return text


def apply_versions(data, version, files, note=None):
    """Rewrite the App version, description, badges and notices for the given pins.

    `files` maps the names in VERSIONED_FILES to their current text; the result
    maps them to the updated text. The release gate feeds the stable files in
    and accepts a candidate only when it equals this output.
    """
    result = {}
    config = files['config.yaml']
    config = _replace_line(config, VERSION_LINE.pattern, f'version: "{version}"', 'config.yaml version')
    config = _replace_line(config, r'^description: ".*"$', f'description: "{description(data)}"',
                           'config.yaml description')
    result['config.yaml'] = config

    changelog = files['CHANGELOG.md']
    if not changelog.startswith(CHANGELOG_HEAD):
        raise ValueError('CHANGELOG.md must start with "# Changelog"')
    note = note or (f'Update CWA to {data["cwa"]["version"]} and '
                    f'Shelfmark to {data["shelfmark"]["version"]}.')
    result['CHANGELOG.md'] = (f'{CHANGELOG_HEAD}## {version}\n\n### Changed\n\n- {note}\n\n'
                              + changelog[len(CHANGELOG_HEAD):])

    readme = files['README.md']
    for name in REPOSITORIES:
        readme = _replace_line(readme, r'^\[!\[' + LABELS[name] + r' version\]\(.*$', badge(name, data),
                               'README.md ' + LABELS[name] + ' badge')
    result['README.md'] = readme

    notice = files['NOTICE.md']
    for name, heading in (('cwa', 'Calibre-Web Automated'), ('shelfmark', 'Shelfmark')):
        pattern = r'(?<=## ' + heading + r'\n\n- Project: )(.*)\n- Version currently packaged: .*$'
        match = re.search(pattern, notice, re.M)
        if not match:
            raise ValueError('Cannot update NOTICE.md ' + heading)
        notice = notice[:match.start()] + match[1] + '\n- Version currently packaged: ' + \
            data[name]['version'] + notice[match.end():]
    result['NOTICE.md'] = notice
    return result


def request(url, github=False):
    headers = {'User-Agent': 'Calibre-AIO-upstream-updater'}
    if github and os.environ.get('GH_TOKEN'):
        headers['Authorization'] = 'Bearer ' + os.environ['GH_TOKEN']
    return urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=60)


def latest(name, known=None):
    return release(name, None, known)


def release(name, tag, known=None):
    """Resolve the latest (or the given) stable release to a commit and archive checksum."""
    repository = REPOSITORIES[name]
    endpoint = 'latest' if tag is None else 'tags/' + tag
    if tag is not None and not re.fullmatch(r'v?\d+\.\d+\.\d+', tag):
        raise ValueError('Only stable version tags are eligible')
    with request(f'https://api.github.com/repos/{repository}/releases/{endpoint}', True) as response:
        info = json.load(response)
    version = info['tag_name']
    if (info.get('draft') or info.get('prerelease') or tag not in (None, version)
            or not re.fullmatch(r'v?\d+\.\d+\.\d+', version)):
        raise ValueError('Only stable version tags are eligible')
    with request(f'https://api.github.com/repos/{repository}/commits/{version}', True) as response:
        commit = json.load(response)['sha']
    if not re.fullmatch(r'[0-9a-f]{40}', commit):
        raise ValueError('Invalid upstream commit')
    # The pinned release still points at the pinned commit: its archive was
    # verified when it was pinned, so an hourly check needs no download.
    if known and known.get('version') == version and known.get('commit') == commit:
        return dict(known)
    digest = hashlib.sha256()
    with request(f'https://github.com/{repository}/archive/{commit}.tar.gz') as response:
        for chunk in iter(lambda: response.read(1024 * 1024), b''):
            digest.update(chunk)
    return dict(repository=repository, version=version, commit=commit, sha256=digest.hexdigest())


def chromium_pins(dockerfile):
    return re.findall(r'^ARG (CHROMIUM_(?:VERSION|SNAPSHOT))=(\S+)$', dockerfile, re.M)


def check_chromium(commit):
    """Refuse a Shelfmark update whose Chromium pin differs from the bundled one."""
    url = f'https://raw.githubusercontent.com/{REPOSITORIES["shelfmark"]}/{commit}/Dockerfile'
    with request(url) as response:
        wanted = chromium_pins(response.read().decode())
    if len(wanted) != 2 or wanted != chromium_pins((ROOT / 'Dockerfile').read_text()):
        raise ValueError('Shelfmark changed its Chromium pin; update the Dockerfile first')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['check', 'render', 'args', 'update', 'versions'])
    parser.add_argument('--component', choices=['all', 'cwa', 'shelfmark'], default='all')
    parser.add_argument('--cwa-version', help='pin this CWA release instead of the latest')
    parser.add_argument('--shelfmark-version', help='pin this Shelfmark release instead of the latest')
    args = parser.parse_args()
    data = load_manifest()
    if args.command == 'versions':
        print('\n'.join(f'{name}={data[name]["version"]}' for name in REPOSITORIES))
        return
    if args.command == 'args':
        print('BUILD_VERSION=' + app_version((ROOT / 'config.yaml').read_text()))
        print('\n'.join(f'{key}={value}' for key, value in arguments(data).items()))
        return
    if args.command == 'update':
        updated = dict(data)
        for name in REPOSITORIES:
            if args.component in ('all', name):
                tag = getattr(args, name + '_version')
                candidate = release(name, tag, data[name]) if tag else latest(name, data[name])
                # Never silently replace the contents of an already-pinned release.
                if candidate['version'] == data[name]['version']:
                    if candidate != data[name]:
                        raise ValueError('Pinned release provenance changed: ' + name)
                else:
                    if tuple(map(int, candidate['version'].lstrip('v').split('.'))) <= tuple(
                            map(int, data[name]['version'].lstrip('v').split('.'))):
                        raise ValueError('Refusing an upstream downgrade: ' + name)
                    if name == 'shelfmark':
                        check_chromium(candidate['commit'])
                    updated[name] = candidate
        if updated == data:
            print('No upstream updates')
            return
        data = updated
        files = {name: (ROOT / name).read_text() for name in VERSIONED_FILES}
        version = next_version(app_version(files['config.yaml']))
        (ROOT / 'upstream.json').write_text(json.dumps(data, indent=2) + '\n')
        for name, text in apply_versions(data, version, files).items():
            (ROOT / name).write_text(text)
    generated = render(data)
    if args.command == 'check':
        if (ROOT / 'build.yaml').read_text() != generated:
            raise SystemExit('build.yaml differs from upstream.json; run scripts/upstreams.py render')
        files = {name: (ROOT / name).read_text() for name in VERSIONED_FILES}
        expected = apply_versions(data, app_version(files['config.yaml']), files, note='x')
        # The versioned files must already carry the pinned versions.
        for name in ('config.yaml', 'README.md', 'NOTICE.md'):
            if expected[name] != files[name]:
                raise SystemExit(name + ' does not carry the pinned versions; run scripts/upstreams.py render')
    else:
        (ROOT / 'build.yaml').write_text(generated)
        if args.command == 'render':
            files = {name: (ROOT / name).read_text() for name in VERSIONED_FILES}
            for name, value in apply_versions(data, app_version(files['config.yaml']), files, note='x').items():
                if name != 'CHANGELOG.md':
                    (ROOT / name).write_text(value)


if __name__ == '__main__':
    main()
